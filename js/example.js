/* 2단계는 답이 길어 끊기지 않도록 하루를 세 구간으로 나눠 받는다 (분 단위, to는 미포함) */
const DAY_PARTS = [
  { key: 'am', label: '오전', range: '~12시', from: 0, to: 12 * 60, span: '기상부터 11:59까지' },
  { key: 'pm', label: '오후', range: '12~18시', from: 12 * 60, to: 18 * 60, span: '12:00부터 17:59까지' },
  // 저녁은 자정을 넘긴 새벽(다음 날 00:40 취침 등)까지 포함한다
  { key: 'eve', label: '저녁', range: '18시~', from: 18 * 60, to: 48 * 60, span: '18:00부터 취침까지' },
];

/**
 * 2단계 OOC: 생성된 집의 공간명·연결을 넣어 만든다 ("오전/오후/저녁" 복사 버튼)
 * part: DAY_PARTS 중 하나. starts: 이미 붙여넣은 동선 기준 캐릭터별 마지막 공간 { PC: '주방', ... }
 */
function buildScheduleTemplate(house, names = [], part = DAY_PARTS[0], starts = {}) {
  const [n1, n2] = names.map((n) => String(n || '').trim());
  const isFirst = part.key === DAY_PARTS[0].key;
  const prev = DAY_PARTS[DAY_PARTS.findIndex((p) => p.key === part.key) - 1];
  const byFloor = house.floors.map((f) => {
    const names = house.rooms.filter((r) => r.floor === f.floor).map((r) => r.name);
    return house.floors.length > 1 ? `- ${f.label}: ${names.join(', ')}` : `- ${names.join(', ')}`;
  });
  const conns = house.connections.map((c) => `- ${c.a} ↔ ${c.b}`);
  // 예시 줄은 침실처럼 보이는 공간에서 시작한다
  const bed = (house.rooms.find((r) => /침실|bed/i.test(r.name)) || house.rooms[0]).name;
  const first = house.connections.find((c) => c.a === bed || c.b === bed) || house.connections[0];
  const a = first ? (first.b === bed ? first.b : first.a) : bed;
  const b = first ? (first.b === bed ? first.a : first.b) : bed;
  // 출력 예시: 오전은 침실에서 일어나 옆 공간으로 가는 두 줄, 이어 받는 구간은 시작 공간에 머무는 한 줄
  const hh = String(Math.floor(part.from / 60)).padStart(2, '0');
  const SAMPLE_ACTION = { pm: '점심 식사', eve: '저녁 식사' };
  const sample = isFirst
    ? (first
      ? `07:00 | PC | 기상 | ${a} | (벌써 아침이네)\n07:05 | PC | 이동 | ${a}>${b} | 좋은 아침`
      : `07:00 | PC | 기상 | ${a} | (벌써 아침이네)`)
    : `${hh}:00 | PC | ${SAMPLE_ACTION[part.key] || '휴식'} | ${starts.PC || a} |`;
  // 이어 받는 구간은 캐릭터가 직전 구간에서 끝난 공간을 알려 준다
  const startList = Object.entries(starts).map(([id, room]) => `${id}는 ${room}`).join(', ');
  const continuity = isFirst ? '' : startList
    ? `\n- 각 캐릭터의 첫 줄은 ${prev.label} 동선이 끝난 공간에서 시작한다: ${startList}.`
    : `\n- 각 캐릭터의 첫 줄은 앞서 출력한 ${prev.label} 동선에서 그 캐릭터가 마지막으로 있던 공간에서 시작한다.`;
  const charRule = !isFirst
    ? '- [CHARACTERS]는 쓰지 않고 [SCHEDULE]만 출력한다.'
    : n1 || n2
      ? '- [CHARACTERS]는 [출력 형식]의 두 줄을 그대로 쓴다.'
      : '- CHARACTER의 name에는 그 캐릭터의 실제 이름을 쓴다.';
  const charBlock = isFirst
    ? `[CHARACTERS]\nCHARACTER: PC | name=${n1 || 'PC 이름'}\nCHARACTER: NPC | name=${n2 || 'NPC 이름'}\n\n`
    : '';
  const intro = isFirst
    ? `아래 집 구조에서 PC와 NPC가 보내는 휴일 하루의 동선 중 ${part.label}(${part.span})만 시간 순서대로 아래 형식으로 출력한다. 이후 시간은 다음 요청에서 이어서 받는다.`
    : `앞서 출력한 ${prev.label} 동선에 이어서, 같은 날 ${part.label}(${part.span}) 동선만 시간 순서대로 아래 형식으로 출력한다.`;
  return `[OOC: 잠시 역할극 중단. 조건 : NPC/PC 기존설정, 관계성, 성격, 성향, 말투, 서사, 캐릭터정보, 유저노트, 로어북 종합참고 ${intro} 출력은 [출력 형식]만 사용하며 별도의 설명은 덧붙이지 않는다.

[규칙]
- 이번 출력의 시간은 ${part.span}로 제한한다.${continuity}
- 위치에는 아래 [공간명]의 이름을 글자 하나까지 그대로 쓴다.
- 한 공간에 머무르면 공간명 하나만 쓴다. 이동하면 지나가는 공간을 빠짐없이 > 로 잇는다. > 로 이어진 이웃한 두 공간은 반드시 [연결]에 있어야 한다.
- 캐릭터의 다음 줄은 그 캐릭터가 직전 줄에서 도착한 공간에서 시작한다(순간 이동 금지).
- 대사는 짧게 한 문장으로 쓰고, 속으로 하는 생각은 괄호로 감싼다. 대사가 없으면 비운다. (PC 대사와 생각 임의생성을 허용한다.)
- 두 캐릭터가 대화하면 같은 시각으로 두 줄을 쓴다.
- 시간은 24시간 HH:MM 형식이며 시각순으로 쓴다.
- 시간표의 캐릭터 칸에는 이름 대신 PC 또는 NPC를 쓴다.
${charRule}
- [출력 예시]는 형식을 보여 주는 예시일 뿐이며 그대로 옮겨 쓰지 않는다.

[공간명]
${byFloor.join('\n')}

[연결]
${conns.join('\n')}

[출력 형식]
${charBlock}[SCHEDULE]
HH:MM | PC 또는 NPC | 행동 | 공간명 또는 공간A>공간B | 대사

[출력 예시]
${sample}
]`;
}
